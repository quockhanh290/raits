"""monitor/test_runner_state_provenance_20260924.py — a stale legacy file must not speak as today.

Plan stage 0, "thôi nói sai". Measured 2026-09-24 against the running backend:

    GET /api/v1/runner-state
      observed_at   2026-08-24T06:58:47Z        age_seconds 2,737,837  (31.7 days)
      freshness     not_expected_yet            <- the schedule's answer, not the file's
      payload.meta.broker_equity          996,730.93   (the paper account held 251,341)
      payload.runner_health.ibkr_connected     true    (heartbeat "2026-08-24")

`not_expected_yet` came from the schedule: in track1-only mode the legacy runner is never due,
so `expected_next_at` slides forward for ever and nothing calls the payload old. The page read
it as "On schedule · next 01:10". Three more pages (phone, terminal, chart-forward) load the raw
file and printed "Runner alive" and the 996,731 figure with no age anywhere.

The gate the plan set: a 30-day-old `live_state_data.js`, and no field leaves the endpoint
without a stale flag; `ibkr_connected` becomes three states, never `true`.
"""
from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path

import pytest

from monitor.backend import app as app_module
from monitor.backend import runner_state_reader as rsr

ROOT = Path(__file__).resolve().parent.parent

#: The shape of the real file on 2026-09-24, trimmed to one snapshot — every top-level block
#: the runner writes is present, so a block that escapes stamping would be caught here.
_PAYLOAD = {
    "runner_health": {"last_heartbeat": "2026-08-24", "ibkr_connected": True},
    "meta": {"account": 50000.0, "broker_equity": 996730.93, "net_pnl": 408.25,
             "final_equity": 50408.25, "max_dd_pct": 0.0, "total_days": 11,
             "operational_status": {"runner": {"alive": True, "pid": 12020},
                                    "breaker": {"level": "OK"}, "regime_unreliable": False},
             "events": [{"ts": "2026-08-24T06:55:13+00:00", "level": "INFO",
                         "category": "STATE", "message": "Runner started"}]},
    "snapshots": [{"date": "2026-08-24", "equity": 50408.25, "open_positions": [],
                   "operational_status": {"breaker": {"level": "OK"}}}],
}


def _write_live_state(path: Path, age_seconds: float) -> Path:
    path.write_text("// Auto-generated by FuturesRunner.dump_state — DO NOT EDIT\n"
                    "window.LIVE_DATA = " + json.dumps(_PAYLOAD) + ";\n", encoding="utf-8")
    then = time.time() - age_seconds
    os.utime(path, (then, then))
    return path


@pytest.fixture
def client_for(monkeypatch, tmp_path):
    """The real endpoint, pointed at a temp tree. The schedule is stubbed to give exactly the
    answer it gave on 2026-09-24 — `not_expected_yet` — because that answer is the lie."""
    def make(age_seconds: float):
        live = _write_live_state(tmp_path / "live_state_data.js", age_seconds)
        monkeypatch.setattr(app_module, "LIVE_STATE_PATH", live)
        monkeypatch.setattr(app_module, "ROOT", tmp_path)
        monkeypatch.setattr(app_module, "resolve_track1_only", lambda: True)
        monkeypatch.setattr(app_module, "get_schedule_status",
                            lambda *a, **k: {"freshness": "not_expected_yet",
                                             "expected_next_at": "2026-09-25T05:10:00Z"})
        return app_module.app.test_client()
    return make


THIRTY_DAYS = 30 * 86400


def test_a_thirty_day_old_file_is_declared_stale_not_on_schedule(client_for):
    body = client_for(THIRTY_DAYS).get("/api/v1/runner-state").get_json()
    assert body["stale"] is True and body["current"] is False
    assert body["source_era"] == "legacy"
    assert "retired" in body["producer"]
    # The schedule's answer is kept — named for what it is — and no longer speaks for the file.
    assert body["freshness"] == "stale"
    assert body["schedule_freshness"] == "not_expected_yet"
    assert body["provenance"]["as_of"] == body["observed_at"]


def test_retired_legacy_health_is_not_served_as_current(client_for):
    body = client_for(THIRTY_DAYS).get("/api/v1/runner-state").get_json()
    assert "legacy_payload" not in body
    health = body["payload"]["runner_health"]
    assert health.get("ibkr_connected") is not True
    # What the file said is not destroyed — it is moved to a name that cannot be read as now.
    assert "ibkr_connected_reported" not in health


def test_no_block_leaves_the_endpoint_without_a_stale_flag(client_for):
    """The walk the plan asked for. Every top-level key is either envelope metadata or a block
    carrying `_provenance.stale`; every payload block and every snapshot is stamped too.

    Asserts the walk is non-empty before trusting it — a walk over nothing passes."""
    body = client_for(THIRTY_DAYS).get("/api/v1/runner-state").get_json()

    derived = [k for k in body if k not in rsr.ENVELOPE_KEYS]
    assert derived, "no derived blocks at all — the walk below would check nothing"
    for key in derived:
        block = body[key]
        assert isinstance(block, dict) and block.get("_provenance", {}).get("stale") is True, (
            f"top-level {key!r} leaves the endpoint with no stale flag")

    # Plan stage 2 moved the legacy file to `legacy_payload`; `payload` is Track 1's now and is
    # held to its own rule in test_runner_state_track1_payload_20260924.py.
    payload = body["legacy_payload"]
    assert payload["_provenance"]["stale"] is True
    blocks = [k for k, v in payload.items() if isinstance(v, dict) and k != "_provenance"]
    assert set(blocks) >= {"meta", "runner_health"}, blocks
    for key in blocks:
        assert payload[key]["_provenance"]["stale"] is True, f"payload.{key} unstamped"
    assert payload["snapshots"], "no snapshots — the per-item check would be vacuous"
    for snap in payload["snapshots"]:
        assert snap["_provenance"]["stale"] is True, f"snapshot {snap.get('date')} unstamped"


def test_a_fresh_file_is_left_to_the_schedule_and_says_connected(client_for):
    """The other direction — without it, the tests above pass for a stamp that is always on."""
    body = client_for(3600).get("/api/v1/runner-state").get_json()
    assert body["stale"] is False and body["current"] is True
    assert body["freshness"] == "not_expected_yet"
    assert "schedule_freshness" not in body
    assert body["legacy_payload"]["runner_health"]["ibkr_connected"] == "connected"
    assert body["legacy_payload"]["meta"]["_provenance"]["stale"] is False


def test_the_raw_file_route_carries_its_age_for_the_three_pages_that_load_it(client_for):
    resp = client_for(THIRTY_DAYS).get("/live_state_data.js")
    text = resp.get_data(as_text=True)
    assert text.startswith("// Auto-generated by FuturesRunner.dump_state"), (
        "the legacy runner's bytes must be served unchanged ahead of the added line")
    m = re.search(r"window\.LIVE_DATA_PROVENANCE = (\{.*\});", text)
    assert m, "no provenance assignment appended"
    prov = json.loads(m.group(1))
    assert prov["stale"] is True and prov["era"] == "legacy"


def test_the_pages_that_load_the_raw_file_read_the_provenance():
    live = (ROOT / "global_index" / "dash" / "shared" / "live.js").read_text(encoding="utf-8")
    assert "LIVE_DATA_PROVENANCE" in live
    # Absent provenance must default to stale, not to current.
    assert re.search(r"stale:\s*true", live), "missing provenance does not default to stale"
    for page in ("phone.html", "terminal.html", "chart-forward.html"):
        html = (ROOT / "global_index" / "dash" / page).read_text(encoding="utf-8")
        assert "shared/live.js" in html, f"{page} no longer goes through live.js"


def test_the_page_and_the_server_use_one_staleness_line():
    src = (ROOT / "global_index" / "dash" / "realtime" / "realtime.js").read_text(encoding="utf-8")
    m = re.search(r"const LEGACY_STALE_HOURS = (\d+);", src)
    assert m, "LEGACY_STALE_HOURS no longer declared in realtime.js"
    assert int(m.group(1)) * 3600 == rsr.LEGACY_STALE_AFTER_SECONDS


def test_the_rail_does_not_take_breaker_or_entry_block_from_a_stale_snapshot():
    src = (ROOT / "global_index" / "dash" / "realtime" / "realtime.js").read_text(encoding="utf-8")
    assert "const stripOps = currentLegacyOps(snap);" in src
    assert "const monitorOps = currentLegacyOps(snap);" in src
    fn = re.search(r"function currentLegacyOps\(snap\) \{(.*?)\n  \}", src, re.S)
    assert fn and "legacyRunnerStale()" in fn.group(1)
